#!/usr/bin/env python3
"""Generate mock/src/routes.js (routes + fixtures + OpenAPI) from the bank's test-customer file and mock/services.json.

    python3 mock/build_routes.py <test-customers.json> [mock/services.json] [mock/src/routes.js]

services.json maps each service name of the test file to its HTTP route, from the bank's integration document:
  {"cards.list": {"method": "POST", "path": "/...", "operationId": "...", "summary": "...",
                  "customer": "body.customerNo",            # where the customer number is in the request
                  "card": "body.cardNumber",                # services keyed by card (second key in the test file)
                  "week": "body.newStatementWeek",          # services keyed by requested week (third key)
                  "request": {"customerNo": {"type": "string", "description": "..."}, ...},   # request fields
                  "required": ["customerNo"],
                  "not_found": {"status": 404, "body": {...}}}}   # answer for a key not in the test file
The test file: customers[].customerNo and customers[].services[<service>] = {http, response|yanit, gecikmeSaniye?},
nested under the masked card number (and the requested week) for card/week services.
"""
import json
import sys


def entry(x):
    body = x.get("response", x.get("yanit"))
    e = {"status": int(x.get("http", 200)), "body": body}
    if x.get("gecikmeSaniye"):
        e["delay_ms"] = int(float(x["gecikmeSaniye"]) * 1000)
    return e


def flatten(v, depth):
    """{key path tuple: entry} for a service value nested `depth` levels below the customer."""
    out = {}
    if depth == 0 or (isinstance(v, dict) and "http" in v):
        out[()] = entry(v)
        return out
    for k, sub in v.items():
        for tail, e in flatten(sub, depth - 1).items():
            out[(str(k),) + tail] = e
    return out


def schema_of(x):
    if isinstance(x, bool):
        return {"type": "boolean"}
    if isinstance(x, int):
        return {"type": "integer"}
    if isinstance(x, float):
        return {"type": "number"}
    if isinstance(x, str):
        return {"type": "string"}
    if x is None:
        return {"type": "string", "nullable": True}
    if isinstance(x, list):
        return {"type": "array", "items": schema_of(x[0]) if x else {}}
    return {"type": "object", "properties": {k: schema_of(v) for k, v in x.items()}}


def main(tc_path, svc_path="mock/services.json", out_path="mock/src/routes.js"):
    tc = json.load(open(tc_path))
    svcs = json.load(open(svc_path))
    routes, paths = [], {}
    env = svcs.get("_envelope") or {}
    for name, s in svcs.items():
        if name.startswith("_"):
            continue
        keys = [s["customer"]] + ([s["week"]] if s.get("week") else [])
        by_customer = s["customer"].endswith(".customerNo")       # else keyed by the card (levels below the customer)
        depth = len(keys) - 1 if by_customer else len(keys)
        fixtures, example = {}, None
        for cu in tc["customers"]:
            v = (cu.get("services") or {}).get(name)
            if v is None:
                continue
            for tail, e in flatten(v, depth).items():
                k = "|".join(((str(cu["customerNo"]),) if by_customer else ()) + tail)
                fixtures[k] = e
                if example is None and e["status"] == 200:
                    example = e["body"]
        route = {"method": s["method"], "path": s["path"], "operationId": s.get("operationId", name.replace(".", "_")),
                 "key": keys if len(keys) > 1 else keys[0], "normalize": "trim", "fixtures": fixtures,
                 "default": s.get("not_found") or {"status": 404, "body": {"error": "not_found"}}}
        if s.get("validate"):
            route["validate"] = s["validate"]
        routes.append(route)
        fields = {f: dict(fs) for f, fs in (s.get("request") or {}).items()}
        req = list(s.get("required") or [])
        inner = {"type": "object", "required": req, "properties": fields}
        if env.get("name"):
            schema = {"type": "object", "required": [env["name"]], "properties": dict({env["name"]: inner}, **(env.get("extra") or {}))}
        else:
            schema = inner
        op = {"operationId": route["operationId"], "summary": s.get("summary", name),
              "requestBody": {"required": True, "content": {"application/json": {"schema": schema}}},
              "responses": {"200": {"description": "success", "content": {"application/json": {"schema": schema_of(example or {})}}}}}
        paths.setdefault(s["path"], {})[s["method"].lower()] = op
        print("%-24s %s %s: %d fixtures" % (name, s["method"], s["path"], len(fixtures)))
    openapi = {"openapi": "3.0.3", "info": {"title": "Bank services mock", "version": "1"}, "servers": [{"url": "/"}], "paths": paths}
    js = ("// GENERATED by mock/build_routes.py from the bank's test-customer file and mock/services.json. Do not edit.\n"
          "export const config = %s;\n"
          "export const routes = %s;\n"
          "export const openapi = %s;\n" % (json.dumps(svcs.get("_config") or {}), json.dumps(routes, ensure_ascii=False, indent=1), json.dumps(openapi, ensure_ascii=False, indent=1)))
    open(out_path, "w").write(js)
    print("wrote %s (%d routes, %d KB)" % (out_path, len(routes), len(js) // 1024))


if __name__ == "__main__":
    main(*sys.argv[1:])
